# --------------------------------------------------------------------------- #
# _provider_model_list(): env override of the offered models
# --------------------------------------------------------------------------- #
class TestProviderModelList:
    def test_env_override_replaces_and_trims_the_list(self, monkeypatch):
        monkeypatch.setenv("QCB_ANTHROPIC_MODELS", "m1, m2 ,m3")
        assert core._provider_model_list("anthropic", ["default"]) == ["m1", "m2", "m3"]

    def test_blank_override_returns_a_defensive_copy_of_the_default(self, monkeypatch):
        monkeypatch.delenv("QCB_GEMINI_MODELS", raising=False)
        default = ["a", "b"]
        out = core._provider_model_list("gemini", default)
        assert out == default
        assert out is not default  # callers must not mutate the catalog default


# --------------------------------------------------------------------------- #
# run_quantum(): force-Aer happy path + unknown-provider sad path
# --------------------------------------------------------------------------- #
class TestRunQuantum:
    def test_force_aer_measures_locally(self):
        pytest.importorskip("qiskit_aer")
        counts, label = core.run_quantum(
            spec(1, [{"name": "x", "qubits": [0]}], mode="qsim"), force_aer=True)
        # Deterministic X on q0: every one of the default 1024 shots reads "1".
        assert counts == {"1": 1024}
        assert "aer" in label.lower()

    def test_unknown_provider_raises_503(self, monkeypatch):
        monkeypatch.setattr(core, "QUANTUM_PROVIDER", "nonsense")
        with pytest.raises(HTTPException) as e:
            core.run_quantum(spec(1, [{"name": "h", "qubits": [0]}], mode="quantum"))
        assert e.value.status_code == 503


# --------------------------------------------------------------------------- #
# explain_circuit(): dispatch guards (no real LLM call)
# --------------------------------------------------------------------------- #
class TestExplainDispatchGuards:
    def test_no_provider_available_raises_403(self, monkeypatch):
        monkeypatch.setattr(core, "default_provider", lambda: None)
        with pytest.raises(HTTPException) as e:
            core.explain_circuit(spec(1, [{"name": "h", "qubits": [0]}]))
        assert e.value.status_code == 403

    def test_explicit_unready_provider_raises_403(self, monkeypatch):
        monkeypatch.setattr(core, "provider_ready", lambda name: False)
        with pytest.raises(HTTPException) as e:
            core.explain_circuit(spec(1, [{"name": "h", "qubits": [0]}]),
                                 provider="anthropic")
        assert e.value.status_code == 403

    def test_happy_path_dispatches_to_handler_with_grounded_prompt(self, monkeypatch):
        # Swap in a fake handler so the full dispatch runs without a real LLM, and
        # assert the model is handed the real, grounded circuit summary.
        captured: dict = {}

        def fake_handler(messages, system, model, key):
            captured["messages"] = messages
            captured["system"] = system
            captured["model"] = model
            return "OK"

        monkeypatch.setattr(core, "_AI_PROVIDERS", {"anthropic": fake_handler})
        monkeypatch.setattr(core, "provider_ready", lambda name: name == "anthropic")
        monkeypatch.setattr(core, "default_provider", lambda: "anthropic")
        out = core.explain_circuit(
            spec(2, [{"name": "h", "qubits": [0]}, {"name": "cx", "qubits": [0, 1]}]),
            provider="anthropic")
        assert out == "OK"
        # The latest user turn carries the grounded summary (gate list + outcomes).
        assert "Gates in order" in captured["messages"][-1]["content"]
        assert core._TEACHING_CONTRACT in captured["system"]
